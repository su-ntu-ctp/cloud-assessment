# Define a function to sum two numbers.
def add(a, b):
  return a + b

# Define a function to calculate the average of a list of numbers.
def average(numbers):
  return sum(numbers) / len(numbers)

# Define a function to say, "Hello, <name>!" where name is the first argument.
def hello(name):
  return f"Hello, {name}!"

# Define a function that takes a boolean value and returns "yes" or "no".
def yes_or_no(boolean):
  return "yes" if boolean else "no"